SELECT DISTINCT C.CAR_ID, C.CAR_TYPE,
    C.DAILY_FEE * 30 * ((100-P.DISCOUNT_RATE)/100) AS 'FEE'
    
FROM CAR_RENTAL_COMPANY_CAR AS C
JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN AS P
ON C.CAR_TYPE = P.CAR_TYPE
AND P.DURATION_TYPE = '30일 이상'

WHERE C.CAR_TYPE IN ('SUV', '세단') AND
    NOT EXISTS (
    SELECT 1
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY AS H
    WHERE H.CAR_ID = C.CAR_ID
      AND H.START_DATE <= '2022-11-30'
      AND H.END_DATE >= '2022-11-01'
) AND
    (CASE
        WHEN C.CAR_TYPE = '세단' THEN C.DAILY_FEE * 0.9
        WHEN C.CAR_TYPE = 'SUV' THEN C.DAILY_FEE * 0.92
    END * 30
) BETWEEN 500000 AND 1999999
    
ORDER BY FEE DESC, C.CAR_TYPE ASC, C.CAR_ID DESC